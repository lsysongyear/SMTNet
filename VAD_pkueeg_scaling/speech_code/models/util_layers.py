import torch


# ============================================================================
# Permute - 维度重排层
# ============================================================================
class Permute(torch.nn.Module):
    """
    将输入张量按指定的维度顺序重新排列。

    用途：在 nn.Sequential 中无法直接使用 torch.permute，
    使用此模块可以在配置驱动的模型构建中灵活调整张量形状。

    示例：
        Permute((0, 2, 1)) 将 [B, C, T] 转为 [B, T, C]
    """
    def __init__(self, dims):
        super().__init__()
        self.dims = dims  # 目标维度顺序


    def forward(self, x):
        return torch.permute(x, self.dims)
